import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const envPath = resolve(root, '.env');
const outPath = resolve(root, 'supabase-config.js');

function parseEnv(text) {
  const values = {};
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const index = trimmed.indexOf('=');
    if (index < 0) continue;
    const key = trimmed.slice(0, index).trim();
    let value = trimmed.slice(index + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

let env = {};
try {
  env = parseEnv(await readFile(envPath, 'utf8'));
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

function firstValue(values, names) {
  for (const name of names) {
    const value = values[name]?.trim();
    if (value) return value;
  }
  return '';
}

function isPublicKey(key) {
  if (/^sb_publishable_[\w-]+$/.test(key)) return true;
  try {
    const parts = key.split('.');
    if (parts.length !== 3) return false;
    const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
    return payload.role === 'anon';
  } catch {
    return false;
  }
}

const urlNames = ['NEXT_PUBLIC_SUPABASE_URL', 'SUPABASE_URL'];
const keyNames = ['NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY', 'NEXT_PUBLIC_SUPABASE_ANON_KEY', 'SUPABASE_ANON_KEY'];
const url = firstValue(process.env, urlNames) || firstValue(env, urlNames);
const key = firstValue(process.env, keyNames) || firstValue(env, keyNames);

if (process.env.REQUIRE_SUPABASE_CONFIG === '1' && (!url || !key)) {
  throw new Error('GitHub Actions의 Supabase URL과 공개 키 변수를 설정해 주세요.');
}
if (key && !isPublicKey(key)) {
  throw new Error('브라우저용 Supabase publishable 키 또는 anon 키가 필요합니다.');
}

const source = `// Generated by scripts/write-supabase-config.mjs.
export const SUPABASE_URL = ${JSON.stringify(url)};
export const SUPABASE_ANON_KEY = ${JSON.stringify(key)};
`;

await writeFile(outPath, source);
if (!url || !key) {
  console.warn('supabase-config.js 생성: .env에 URL/키가 비어 있습니다. 로컬 저장 모드로 동작합니다.');
} else {
  console.log('공개 Supabase 연결 설정을 생성했습니다.');
}
